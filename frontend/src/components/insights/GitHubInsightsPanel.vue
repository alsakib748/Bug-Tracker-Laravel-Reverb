<template>
  <ComponentCard
    title="GitHub health insights"
    desc="AI explanation of the GitHub velocity metrics above. The model only interprets the supplied metrics — it never counts.">
    <div class="flex flex-wrap items-center justify-between gap-3">
      <p class="text-xs text-gray-500 dark:text-gray-400">
        Grounded in your stored pull request and commit data.
      </p>
      <button
        class="px-3 py-1.5 text-xs text-white bg-blue-600 rounded-md disabled:opacity-50"
        :disabled="loading || !projectId"
        @click="analyze">
        <i class="mr-1 pi" :class="loading ? 'pi-spin pi-spinner' : 'pi-sparkles'"></i>
        {{ loading ? 'Analyzing…' : 'Analyze GitHub health' }}
      </button>
    </div>

    <div v-if="error"
      class="p-3 text-sm text-red-700 bg-red-50 rounded-md dark:bg-red-900/20 dark:text-red-300">
      {{ error }}
    </div>

    <div v-else-if="loading" class="py-6 text-center text-sm text-gray-500">
      <i class="mr-2 pi pi-spin pi-spinner"></i>
      Analyzing development velocity…
    </div>

    <template v-else-if="insight?.result">
      <p class="text-sm font-medium text-gray-800 dark:text-gray-200">{{ insight.result.summary }}</p>

      <div v-if="insight.result.findings?.length" class="space-y-2">
        <div v-for="(finding, index) in insight.result.findings" :key="index"
          class="p-3 border border-l-2 rounded-md border-l-blue-400 dark:border-gray-800">
          <div class="flex items-center justify-between">
            <span class="text-sm font-medium text-gray-800 dark:text-gray-200">{{ finding.title }}</span>
            <span class="px-2 py-0.5 text-xs rounded-full" :class="confidenceClass(finding.confidence)">
              {{ finding.confidence }}
            </span>
          </div>
          <p class="mt-1 text-sm text-gray-600 dark:text-gray-400">{{ finding.interpretation }}</p>
          <div v-if="finding.evidence?.length" class="flex flex-wrap gap-1 mt-2">
            <span v-for="metric in finding.evidence" :key="metric"
              class="px-2 py-0.5 text-xs font-mono bg-gray-100 rounded dark:bg-gray-800 dark:text-gray-300">
              {{ metric }}
            </span>
          </div>
        </div>
      </div>

      <div v-if="insight.result.recommendations?.length">
        <p class="mb-1 text-xs font-medium text-gray-700 dark:text-gray-300">Suggested next steps</p>
        <ul class="pl-5 text-sm text-gray-600 list-disc dark:text-gray-400">
          <li v-for="(rec, index) in insight.result.recommendations" :key="index">
            <span class="font-medium text-gray-700 dark:text-gray-300">{{ rec.title }}</span> — {{ rec.reason }}
          </li>
        </ul>
      </div>

      <div v-if="insight.result.limitations?.length" class="text-xs italic text-gray-400">
        <p v-for="(limitation, index) in insight.result.limitations" :key="index">• {{ limitation }}</p>
      </div>

      <p class="text-xs text-gray-400">
        Generated by {{ insight.model_provider || 'n/a' }} / {{ insight.model_name || 'n/a' }}
      </p>
    </template>

    <p v-else class="text-xs text-gray-400">
      Click "Analyze GitHub health" to generate a development-velocity summary.
    </p>
  </ComponentCard>
</template>

<script setup>
import { ref, watch, onBeforeUnmount } from 'vue'
import ComponentCard from '@/components/common/ComponentCard.vue'
import { fetchInsight, requestInsight } from '@/services/insightsApi'

const props = defineProps({
  projectId: { type: [Number, String], default: null },
})

const loading = ref(false)
const error = ref(null)
const insight = ref(null)

let cancelled = false

const confidenceClass = (confidence) =>
  ({
    high: 'bg-green-100 text-green-700',
    medium: 'bg-amber-100 text-amber-700',
    low: 'bg-gray-100 text-gray-600',
  })[confidence] || 'bg-gray-100 text-gray-600'

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

const poll = async (id) => {
  for (let attempt = 0; attempt < 30 && !cancelled; attempt += 1) {
    const { data } = await fetchInsight(id)
    const current = data.data

    if (current.status === 'completed') {
      insight.value = current
      return
    }

    if (current.status === 'failed') {
      error.value = `Insight generation failed (${current.error_code || 'unknown'}).`
      return
    }

    await sleep(2000)
  }

  if (!cancelled) {
    error.value = 'Insight is taking longer than expected. Please try again.'
  }
}

const analyze = async () => {
  if (!props.projectId) return

  loading.value = true
  error.value = null
  insight.value = null
  cancelled = false

  try {
    const { data } = await requestInsight(props.projectId, { insight_type: 'github_health' })
    await poll(data.data.id)
  } catch {
    error.value = 'Failed to request the insight.'
  } finally {
    if (!cancelled) {
      loading.value = false
    }
  }
}

watch(
  () => props.projectId,
  () => {
    cancelled = true
    loading.value = false
    error.value = null
    insight.value = null
  },
)

onBeforeUnmount(() => {
  cancelled = true
})
</script>
